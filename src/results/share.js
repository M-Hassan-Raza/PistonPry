import { state } from './state.js';
import { escapeHtml } from '../shared/sanitize.js';
import { showToast } from './toast.js';
import { getProcessedLinks } from './filters.js';

function encodeShareItems(items) {
  const bytes = new TextEncoder().encode(JSON.stringify(items));
  let binary = '';
  bytes.forEach((byte) => {
    binary += String.fromCharCode(byte);
  });
  return btoa(binary);
}

export function generateSharePage() {
  const items = getProcessedLinks();
  if (items.length === 0) {
    showToast('warning', 'No items to share');
    return;
  }

  const title = state.sourceTitle || 'PistonPry Items';
  const encodedItems = encodeShareItems(items.map((l) => ({
    url: l.url, text: l.text || '', type: l.type, domain: l.domain
  })));

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapeHtml(title)}</title>
<style>
body{font-family:system-ui,-apple-system,sans-serif;max-width:900px;margin:40px auto;padding:0 20px;background:#f5f3ef;color:#1a1a1a}
h1{font-size:1.4rem;margin-bottom:8px}
.meta{color:#666;font-size:.85rem;margin-bottom:16px}
input{width:100%;padding:8px 12px;border:1px solid #ddd;border-radius:8px;font-size:.85rem;margin-bottom:12px}
table{width:100%;border-collapse:collapse}
th,td{text-align:left;padding:8px 10px;border-bottom:1px solid #eee;font-size:.85rem}
th{font-weight:600;background:#f0ece6}
a{color:#4f46e5;text-decoration:none}
a:hover{text-decoration:underline}
.text{color:#666;font-size:.8rem}
.pill{display:inline-block;padding:1px 6px;border-radius:100px;font-size:.7rem;background:#eee;color:#666;text-transform:uppercase}
@media(prefers-color-scheme:dark){body{background:#1a1a1a;color:#f0ece6}th{background:#2e2e2e}td{border-color:#333}a{color:#a5b4fc}.meta{color:#999}.text{color:#888}.pill{background:#333;color:#999}input{background:#242424;border-color:#3a3a3a;color:#f0ece6}}
</style>
</head>
<body>
<h1>${escapeHtml(title)}</h1>
<div class="meta">Generated by PistonPry${state.sourceUrl ? ' from ' + escapeHtml(state.sourceUrl) : ''} on ${new Date().toLocaleDateString()}</div>
<input type="text" id="filter" placeholder="Filter items...">
<table><thead><tr><th>#</th><th>URL</th><th>Text</th><th>Type</th></tr></thead><tbody id="tbody"></tbody></table>
<script>
var encodedItems='${encodedItems}';
var bytes=Uint8Array.from(atob(encodedItems),function(ch){return ch.charCodeAt(0)});
var links=JSON.parse(new TextDecoder().decode(bytes));
var tbody=document.getElementById('tbody');
var filterInput=document.getElementById('filter');
function getSafeHref(url){try{var parsed=new URL(url);if(['http:','https:','ftp:','mailto:','tel:'].includes(parsed.protocol)){return parsed.href}}catch{}return''}
function render(items){tbody.textContent='';items.forEach(function(item,index){var row=document.createElement('tr');var indexCell=document.createElement('td');indexCell.textContent=String(index+1);row.appendChild(indexCell);var urlCell=document.createElement('td');var href=getSafeHref(item.url);if(href){var anchor=document.createElement('a');anchor.href=href;anchor.target='_blank';anchor.rel='noopener noreferrer';anchor.textContent=item.url;urlCell.appendChild(anchor)}else{urlCell.textContent=item.url}row.appendChild(urlCell);var textCell=document.createElement('td');var textSpan=document.createElement('span');textSpan.className='text';textSpan.textContent=item.text||'';textCell.appendChild(textSpan);row.appendChild(textCell);var typeCell=document.createElement('td');var typePill=document.createElement('span');typePill.className='pill';typePill.textContent=item.type||'webpage';typeCell.appendChild(typePill);row.appendChild(typeCell);tbody.appendChild(row)})}
function filterLinks(){var value=filterInput.value.toLowerCase();var filtered=links.filter(function(item){return item.url.toLowerCase().includes(value)||(item.text||'').toLowerCase().includes(value)});render(filtered)}
filterInput.addEventListener('input',filterLinks);
render(links);
<\/script>
</body></html>`;

  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'pistonpry-items.html';
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
  showToast('success', 'Shared', 'Shareable HTML page downloaded');
}
